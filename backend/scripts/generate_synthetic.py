"""Generate a labelled synthetic dataset (drawn here, so it carries no third-party licence).

Usage (from backend/):
  python -m scripts.generate_synthetic [--count 10] [--seed 0] [--out DIR] [--classes damaged intact blocked clear]

Each image gets exactly one image-level label, matching the evaluation scripts:
  damaged / intact  judge the boxes (the walkway is always kept clear, so only damage decides the label)
  blocked / clear   judge the walkway (boxes are always undamaged, so only the lane decides the label)

Scenes are rendered with the primitives of make_demo_images, then passed through the same preprocessing as an upload,
renamed after their hash, de-duplicated and added to <out>/manifest.csv by prepare_dataset. Re-running with the same
seed adds nothing new. The default output folder is the gitignored datasets/ directory.
"""

import argparse
import random
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageEnhance

from scripts.dataset_utils import DATASETS_DIR, LABELS
from scripts.make_demo_images import H, W, WALKWAY, Box, scene, stack
from scripts.prepare_dataset import prepare

SOURCE = "synthetic"
LICENSE = "CC0-1.0 (generated by backend/scripts/generate_synthetic.py)"
DAMAGE_TYPES = ("crushed_corner", "tear", "water", "open_flap")

# Stacks never touch the lane in the two background bands; a blocking box is placed with its base inside the lane.
BACK_BASE = 450
FRONT_BASE = 780
LANE_BASE = (575, 610)
SLOT_WIDTH = 260
SLOTS = (W - 80) // SLOT_WIDTH


def _slots(rng: random.Random, count: int) -> list[int]:
    return [40 + s * SLOT_WIDTH for s in rng.sample(range(SLOTS), min(count, SLOTS))]


def _background(rng: random.Random) -> list[Box]:
    """Stacks behind and in front of the lane, clear of it."""
    boxes: list[Box] = []
    for base, max_rows in ((BACK_BASE, 2), (FRONT_BASE, 1)):
        for x in _slots(rng, rng.randint(1, 3)):
            w, h = rng.randint(150, 190), rng.randint(120, 150)
            boxes += stack(x + rng.randint(-10, 10), base, w, h, rng.randint(1, max_rows), tone=rng.randint(0, 3))
    return boxes


def build(label: str, seed: int) -> tuple[Image.Image, list[Box]]:
    """One scene for `label`; returns the image and the boxes drawn (for the geometry checks)."""
    if label not in LABELS:
        raise ValueError(f"label must be one of {list(LABELS)}")
    rng = random.Random(f"{label}:{seed}")
    boxes = _background(rng)
    if label == "damaged":
        for box in rng.sample(boxes, rng.randint(1, min(3, len(boxes)))):
            box.damage = rng.choice(DAMAGE_TYPES)
    elif label == "blocked":
        for x in _slots(rng, rng.randint(1, 2)):
            w, h = rng.randint(160, 200), rng.randint(130, 160)
            boxes += stack(x + rng.randint(-10, 10), rng.randint(*LANE_BASE), w, h, rng.randint(1, 2), tone=rng.randint(0, 3))
    image = scene(rng.randint(0, 2**31 - 1), boxes)
    image = ImageEnhance.Brightness(image).enhance(rng.uniform(0.8, 1.15))
    image = ImageEnhance.Contrast(image).enhance(rng.uniform(0.9, 1.1))
    return image, boxes


def blocks_lane(box: Box) -> bool:
    top, bottom = WALKWAY
    return min(box.base, bottom) - max(box.base - box.h, top) > 0


def generate(out: Path, *, count: int = 10, seed: int = 0, classes: tuple[str, ...] = LABELS) -> dict[str, dict[str, int]]:
    """Render `count` images per class and add them to the dataset at `out`; returns prepare's counts per class."""
    results = {}
    with tempfile.TemporaryDirectory() as tmp:
        for label in classes:
            folder = Path(tmp) / label
            folder.mkdir()
            for i in range(count):
                image, _ = build(label, seed * 100_000 + i)
                image.save(folder / f"{label}_{i:04d}.jpg", format="JPEG", quality=95)
            results[label] = prepare(folder, out, source=SOURCE, license=LICENSE, label=label, n=count, seed=seed)
    return results


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=10, help="images per class")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--out", type=Path, default=DATASETS_DIR)
    parser.add_argument("--classes", nargs="+", choices=LABELS, default=list(LABELS))
    args = parser.parse_args(argv)
    if args.count < 1:
        parser.error("--count must be at least 1")
    for label, counts in generate(args.out, count=args.count, seed=args.seed, classes=tuple(args.classes)).items():
        print(f"{label}: {counts}")
    print(f"Dataset at {args.out} ({W}x{H} scenes, manifest.csv written)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
